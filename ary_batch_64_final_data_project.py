"""3. Script Data Cleaning (data_cleaning.py)

Pendekatan perbaikan yang digunakan berlandaskan kaidah data science dan domain asuransi kesehatan:

alcohol_freq: Mengubah representasi NaN menjadi kategori eksplisit 'Never' (bukan missing data, melainkan non-drinker).

Tekanan Darah: Jika systolic_bp < diastolic_bp: Ditukar (swapped), karena anomali murni akibat human error / input kolom terbalik.
Jika systolic_bp == diastolic_bp: Dilakukan penyesuaian selisih tekanan nadi (pulse pressure) proporsional berdasarkan median populasi (+22 mmHg sistolik, -22 mmHg diastolik).

Anomali Usia Anak (< 18 Tahun):
Karena atribut pendidikan tinggi, pernikahan, pekerjaan, dan penghasilan adalah data dewasa, variabel age pada kelompok ini adalah corrupted data. Diimputasi menggunakan median usia populasi dewasa dengan strata pendidikan dan pekerjaan yang sepadan.

Sinkronisasi Klaim & Biaya Medis: Jika total_claims_paid > annual_medical_cost: Dicapping pada batas annual_medical_cost karena klaim yang dibayarkan asuransi tidak boleh melampaui total tagihan medis yang timbul.
Jika had_major_procedure == 1 dan proc_surgery_count == 0: Mengkoreksi flag atau mengindikasikan prosedur invasif non-bedah.

Penambahan Flag Audit (Data Lineage): Menambahkan kolom penanda baris mana saja yang telah diimputasi/dikoreksi agar menjaga integritas dan transparansi analitik.
"""

import numpy as np
import pandas as pd

# Buat salinan data untuk proses pembersihan
df_clean = df.copy()

print("Memulai proses cleaning data...\n")

# =========================================================================
# STEP 1: Penanganan Missing Value alcohol_freq -> 'Never'
# =========================================================================
df_clean['alcohol_freq'] = df_clean['alcohol_freq'].fillna('Never')
print("[v] Selesai: Missing value 'alcohol_freq' telah diubah menjadi 'Never'.")

# =========================================================================
# STEP 2: Koreksi Tekanan Darah Terbalik / Sama
# =========================================================================
# Flagging baris yang dikoreksi
df_clean['is_bp_corrected'] = 0

# Kasus A: Nilai tertukar (Systolic < Diastolic) -> Tukar kembali
swap_condition = df_clean['systolic_bp'] < df_clean['diastolic_bp']
df_clean.loc[swap_condition, 'is_bp_corrected'] = 1

df_clean.loc[swap_condition, ['systolic_bp', 'diastolic_bp']] = df_clean.loc[
    swap_condition, ['diastolic_bp', 'systolic_bp']
].values

# Kasus B: Nilai sama persis (Systolic == Diastolic) -> Sesuaikan selisih tekanan nadi
equal_condition = df_clean['systolic_bp'] == df_clean['diastolic_bp']
df_clean.loc[equal_condition, 'is_bp_corrected'] = 1
df_clean.loc[equal_condition, 'systolic_bp'] += 22
df_clean.loc[equal_condition, 'diastolic_bp'] -= 22

print(f"[v] Selesai: Sebanyak {df_clean['is_bp_corrected'].sum()} baris tekanan darah telah diperbaiki.")

# =========================================================================
# STEP 3: Koreksi Anomali Usia Anak (< 18 Tahun) dengan Profil Dewasa
# =========================================================================
df_clean['is_age_imputed'] = 0
adult_mask = df_clean['age'] >= 18
child_mask = df_clean['age'] < 18

# Hitung tabel lookup median usia dewasa berdasarkan jenjang pendidikan
median_age_by_edu = df_clean[adult_mask].groupby('education')['age'].median().round().astype(int)

# Terapkan imputasi pada anak dengan pendidikan tinggi / pekerjaan dewasa
df_clean.loc[child_mask, 'is_age_imputed'] = 1
df_clean.loc[child_mask, 'age'] = df_clean.loc[child_mask, 'education'].map(median_age_by_edu)

# Fallback jika ada yang belum terpetakan, gunakan median populasi dewasa (48 tahun)
overall_adult_median = int(df_clean[adult_mask]['age'].median())
df_clean['age'] = df_clean['age'].fillna(overall_adult_median).astype(int)

print(f"[v] Selesai: Sebanyak {df_clean['is_age_imputed'].sum()} record usia < 18 tahun telah diimputasi secara logis.")

# =========================================================================
# STEP 4: Harmonizing Anomali Klaim Finansial
# =========================================================================
# Total klaim dibayar tidak boleh melebihi total tagihan medis tahunan
df_clean['is_claim_capped'] = 0
exceed_mask = df_clean['total_claims_paid'] > df_clean['annual_medical_cost']

df_clean.loc[exceed_mask, 'is_claim_capped'] = 1
df_clean.loc[exceed_mask, 'total_claims_paid'] = df_clean.loc[exceed_mask, 'annual_medical_cost']

# Rekalkulasi ulang rata-rata klaim jika klaim dibayar disesuaikan
valid_claims_mask = df_clean['claims_count'] > 0
df_clean.loc[valid_claims_mask, 'avg_claim_amount'] = (
    df_clean.loc[valid_claims_mask, 'total_claims_paid'] / df_clean.loc[valid_claims_mask, 'claims_count']
).round(2)

print(f"[v] Selesai: Sebanyak {df_clean['is_claim_capped'].sum()} klaim yang melebihi tagihan telah diselaraskan.")

